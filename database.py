    # Portfolio value
    cash = float(conn.execute("SELECT value FROM config WHERE key='current_cash'").fetchone()["value"])
    initial_cap = float(conn.execute("SELECT value FROM config WHERE key='initial_capital'").fetchone()["value"])

    # Holdings P&L
    holdings_df = pd.read_sql("SELECT * FROM holdings WHERE quantity > 0", conn)
    invested = holdings_df["buy_value"].sum() if not holdings_df.empty else 0
    current_holdings_value = holdings_df["current_value"].sum() if not holdings_df.empty else 0
    unrealized_pnl = holdings_df["unrealized_pnl"].sum() if not holdings_df.empty else 0

    # Trades summary
    realized_pnl = pd.read_sql("SELECT COALESCE(SUM(realized_pnl), 0) as total FROM trades WHERE side='SELL'", conn)
    realized_pnl = realized_pnl["total"].iloc[0] if not realized_pnl.empty else 0

    total_trades = pd.read_sql("SELECT COUNT(*) as count FROM trades", conn)["count"].iloc[0]
    winning_trades = pd.read_sql("SELECT COUNT(*) as count FROM trades WHERE realized_pnl > 0", conn)["count"].iloc[0]
    losing_trades = pd.read_sql("SELECT COUNT(*) as count FROM trades WHERE realized_pnl < 0", conn)["count"].iloc[0]

    total_value = cash + current_holdings_value
    total_pnl = realized_pnl + unrealized_pnl
    total_returns_pct = ((total_value - initial_cap) / initial_cap) * 100 if initial_cap > 0 else 0

    # Counts
    total_bought = pd.read_sql("SELECT COALESCE(SUM(quantity), 0) as total FROM trades WHERE side='BUY'", conn)["total"].iloc[0]
    total_sold = pd.read_sql("SELECT COALESCE(SUM(quantity), 0) as total FROM trades WHERE side='SELL'", conn)["total"].iloc[0]
    held_shares = pd.read_sql("SELECT COALESCE(SUM(quantity), 0) as total FROM holdings WHERE quantity > 0", conn)["total"].iloc[0]
    num_positions = pd.read_sql("SELECT COUNT(*) as count FROM holdings WHERE quantity > 0", conn)["count"].iloc[0]

    conn.close()

    return {
        "cash_balance": round(cash, 2),
        "initial_capital": round(initial_cap, 2),
        "invested_value": round(invested, 2),
        "current_holdings_value": round(current_holdings_value, 2),
        "total_portfolio_value": round(total_value, 2),
        "unrealized_pnl": round(unrealized_pnl, 2),
        "realized_pnl": round(realized_pnl, 2),
        "total_pnl": round(total_pnl, 2),
        "total_returns_pct": round(total_returns_pct, 2),
        "total_trades": int(total_trades),
        "winning_trades": int(winning_trades),
        "losing_trades": int(losing_trades),
        "win_rate": round((winning_trades / total_trades * 100), 2) if total_trades > 0 else 0,
        "total_bought_shares": int(total_bought),
        "total_sold_shares": int(total_sold),
        "held_shares": int(held_shares),
        "num_open_positions": int(num_positions),
    }


