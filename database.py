def get_realized_pnl():
    """Get total realized P&L from all completed trades."""
    conn = get_connection()
    result = conn.execute("SELECT COALESCE(SUM(realized_pnl), 0) as total FROM trades WHERE side='SELL'").fetchone()
    conn.close()
    return result["total"]


def get_unrealized_pnl():
    """Get total unrealized P&L from open positions."""
    conn = get_connection()
    result = conn.execute("SELECT COALESCE(SUM(unrealized_pnl), 0) as total FROM holdings WHERE quantity > 0").fetchone()
    conn.close()
    return result["total"]


def get_trade_count():
    """Get total number of trades executed."""
    conn = get_connection()
    result = conn.execute("SELECT COUNT(*) as count FROM trades").fetchone()
    conn.close()
    return result["count"]


def get_winning_trades_count():
    """Get number of winning trades (realized P&L > 0)."""
    conn = get_connection()
    result = conn.execute("SELECT COUNT(*) as count FROM trades WHERE realized_pnl > 0").fetchone()
    conn.close()
    return result["count"]


def get_total_profit():
    """Total realized profit from all winning trades (positive sum)."""
    conn = get_connection()
    result = conn.execute("""
        SELECT COALESCE(SUM(realized_pnl), 0) as total
        FROM trades WHERE side='SELL' AND realized_pnl > 0
    """).fetchone()
    conn.close()
    return result["total"]


def get_total_loss():
    """Total realized loss from all losing trades (reported as a positive number)."""
    conn = get_connection()
    result = conn.execute("""
        SELECT COALESCE(SUM(realized_pnl), 0) as total
        FROM trades WHERE side='SELL' AND realized_pnl < 0
    """).fetchone()
    conn.close()
    return abs(result["total"])


