# --- Trades Operations ---

def record_trade(symbol: str, side: str, quantity: int, price: float,
                  realized_pnl: float = 0, realized_pnl_pct: float = 0,
                  reason: str = "", signal_id: int = None):
    """Record a trade in the database."""
    conn = get_connection()
    now = datetime.now().isoformat()
    slippage = round(price * 0.001, 2)  # 0.1% slippage assumption
    trade_value = round(quantity * price, 2)

    conn.execute("""
        INSERT INTO trades (symbol, side, quantity, price, trade_value, slippage,
            realized_pnl, realized_pnl_pct, timestamp, signal_id, reason)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (symbol, side, quantity, round(price, 2), trade_value, slippage,
          round(realized_pnl, 2), round(realized_pnl_pct, 2), now, signal_id, reason))

    conn.commit()
    conn.close()


