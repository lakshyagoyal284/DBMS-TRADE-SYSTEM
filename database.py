def get_latest_signals_by_symbol():
    """Get the latest signal for each symbol."""
    conn = get_connection()
    df = pd.read_sql("""
        SELECT s.* FROM signals s
        INNER JOIN (
            SELECT symbol, MAX(timestamp) as max_ts
            FROM signals GROUP BY symbol
        ) latest ON s.symbol = latest.symbol AND s.timestamp = latest.max_ts
        ORDER BY s.timestamp DESC
    """, conn)
    conn.close()
    return df


