"""
Database Module
===============
SQLite database for storing all trading data:
- holdings: current portfolio positions
- trades: executed buy/sell trades
- signals: trading signals generated by strategy
- price_snapshots: real-time price data
- portfolio_history: P&L tracking over time
"""

import sqlite3
import pandas as pd
from datetime import datetime
from pathlib import Path

DB_PATH = Path(__file__).parent / "trading_data.db"


def get_connection():
    """Get a database connection."""
    conn = sqlite3.connect(str(DB_PATH))
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA journal_mode=WAL")
    return conn


