# --- Price Alert Tracking ---

def get_last_alert_price(symbol: str) -> float:
    """Get the last price at which a rise alert was sent for a symbol."""
    conn = get_connection()
    result = conn.execute(
        "SELECT last_notified_price FROM price_alerts WHERE symbol = ?", (symbol,)
    ).fetchone()
    conn.close()
    return result["last_notified_price"] if result else 0.0


def update_last_alert_price(symbol: str, price: float):
    """Update the last notified price for a symbol."""
    conn = get_connection()
    now = datetime.now().isoformat()
    conn.execute("""
        INSERT OR REPLACE INTO price_alerts (symbol, last_notified_price, last_notified_at)
        VALUES (?, ?, ?)
    """, (symbol, round(price, 2), now))
    conn.commit()
    conn.close()


def clear_alert_price(symbol: str):
    """Remove alert tracking for a symbol (e.g. after position is closed)."""
    conn = get_connection()
    conn.execute("DELETE FROM price_alerts WHERE symbol = ?", (symbol,))
    conn.commit()
    conn.close()


