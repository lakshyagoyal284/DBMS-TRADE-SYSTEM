# --- Portfolio History Operations ---

def record_portfolio_snapshot(cash: float, invested: float, unrealized_pnl: float,
                               realized_pnl: float, day_pnl: float = 0):
    """Record a portfolio snapshot."""
    conn = get_connection()
    now = datetime.now().isoformat()
    total_value = cash + invested + unrealized_pnl
    initial_capital = float(conn.execute("SELECT value FROM config WHERE key='initial_capital'").fetchone()["value"])
    total_pnl = realized_pnl + unrealized_pnl
    total_returns_pct = ((total_value - initial_capital) / initial_capital) * 100 if initial_capital > 0 else 0

    conn.execute("""
        INSERT INTO portfolio_history (total_value, cash_balance, invested_value,
            unrealized_pnl, realized_pnl, total_pnl, total_returns_pct, day_pnl, timestamp)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (round(total_value, 2), round(cash, 2), round(invested, 2),
          round(unrealized_pnl, 2), round(realized_pnl, 2),
          round(total_pnl, 2), round(total_returns_pct, 2),
          round(day_pnl, 2), now))
    conn.commit()
    conn.close()


def get_portfolio_history(limit: int = 500):
    """Get the most recent portfolio history, ordered oldest -> newest."""
    conn = get_connection()
    df = pd.read_sql(
        f"SELECT * FROM ("
        f"SELECT * FROM portfolio_history ORDER BY timestamp DESC LIMIT {limit}"
        f") ORDER BY timestamp ASC",
        conn,
    )
    conn.close()
    return df


